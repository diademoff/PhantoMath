def _normalize_locale(locale: str) -> str:
    """Same semantics as :func:`mymath_backend.service.normalize_locale`."""
    if locale.strip().lower().split("-")[0] == "ru":
        return "ru"
    return "default"


def _has_cyrillic(text: str) -> bool:
    return any("\u0400" <= ch <= "\u04ff" for ch in text)


