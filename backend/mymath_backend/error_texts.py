def translate(message: str, locale: str) -> str:
    """Return ``message`` in the requested locale.

    Russian locale leaves the message unchanged. Any other locale falls back
    to English using the tables above. Placeholder values that still
    contain Cyrillic are translated recursively.
    """
    if _normalize_locale(locale) == "ru":
        return message

    translated: str | None = None
    if message in EXACT_MESSAGES:
        translated = EXACT_MESSAGES[message]
    else:
        for pattern, template in REGEX_MESSAGES:
            match = pattern.match(message)
            if match is not None:
                groups = list(match.groups())
                for i, value in enumerate(groups):
                    if _has_cyrillic(value):
                        groups[i] = translate(value, "default")
                translated = template
                for i, value in enumerate(groups, start=1):
                    translated = translated.replace("\\" + str(i), value)
                break
    if translated is None:
        return message

    if _has_cyrillic(translated):
        translated = translate(translated, "default")
    return translated


